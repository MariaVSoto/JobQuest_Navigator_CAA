#!/bin/bash

# JobQuest Navigator - Release Packaging Script
# This script packages the entire prod directory for distribution

set -e  # Exit on any error

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Function to print colored output
print_status() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

print_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

print_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Default values
VERSION="1.0.0"
OUTPUT_DIR="../release"
PACKAGE_NAME="jobquest-navigator-production"

# Function to show usage
show_usage() {
    echo "Usage: $0 [OPTIONS]"
    echo "Options:"
    echo "  -v, --version VERSION     Release version (default: $VERSION)"
    echo "  -o, --output DIR          Output directory (default: $OUTPUT_DIR)"
    echo "  -n, --name NAME           Package name (default: $PACKAGE_NAME)"
    echo "  -h, --help               Show this help message"
}

# Parse command line arguments
while [[ $# -gt 0 ]]; do
    case $1 in
        -v|--version)
            VERSION="$2"
            shift 2
            ;;
        -o|--output)
            OUTPUT_DIR="$2"
            shift 2
            ;;
        -n|--name)
            PACKAGE_NAME="$2"
            shift 2
            ;;
        -h|--help)
            show_usage
            exit 0
            ;;
        *)
            print_error "Unknown option: $1"
            show_usage
            exit 1
            ;;
    esac
done

print_status "Starting JobQuest Navigator Release Packaging..."
print_status "Version: $VERSION"
print_status "Package Name: $PACKAGE_NAME"
print_status "Output Directory: $OUTPUT_DIR"

# Create timestamp
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
FULL_PACKAGE_NAME="${PACKAGE_NAME}-v${VERSION}-${TIMESTAMP}"

# Create output directory
mkdir -p "$OUTPUT_DIR"
RELEASE_DIR="$OUTPUT_DIR/$FULL_PACKAGE_NAME"

print_status "Creating release directory: $RELEASE_DIR"
mkdir -p "$RELEASE_DIR"

# =============================================================================
# Copy Production Files
# =============================================================================

print_status "Copying production files..."

# Copy main directories
print_status "Copying backend code..."
cp -r ../backend "$RELEASE_DIR/"

print_status "Copying frontend code..."
cp -r ../frontend "$RELEASE_DIR/"

print_status "Copying infrastructure templates..."
cp -r ../infrastructure "$RELEASE_DIR/"

print_status "Copying configuration files..."
cp -r ../configs "$RELEASE_DIR/"

print_status "Copying documentation..."
cp -r ../docs "$RELEASE_DIR/"

print_status "Copying scripts..."
cp -r ../scripts "$RELEASE_DIR/"

# Create tests directory structure
mkdir -p "$RELEASE_DIR/tests"
if [ -d "../tests" ]; then
    cp -r ../tests/* "$RELEASE_DIR/tests/"
fi

# =============================================================================
# Generate Release Information
# =============================================================================

print_status "Generating release information..."

# Create release info file
cat > "$RELEASE_DIR/RELEASE_INFO.md" << EOF
# JobQuest Navigator Production Release

**Version**: $VERSION  
**Build Date**: $(date)  
**Build ID**: $TIMESTAMP  

## Package Contents

- \`backend/\` - Django REST API backend code
- \`frontend/\` - React frontend application
- \`infrastructure/\` - AWS CloudFormation templates
- \`configs/\` - Configuration files and environment templates
- \`docs/\` - Complete documentation set
- \`scripts/\` - Deployment and management scripts
- \`tests/\` - Test suites and validation scripts

## Quick Start

1. **Prerequisites**:
   - AWS CLI configured
   - Python 3.9+
   - Node.js 18+
   - Docker (optional, for local testing)

2. **Configuration**:
   \`\`\`bash
   cd configs/
   cp environment.env .env
   # Edit .env with your AWS configuration
   \`\`\`

3. **Deploy Infrastructure**:
   \`\`\`bash
   cd scripts/
   ./deploy-infrastructure.sh
   \`\`\`

4. **Deploy Backend**:
   \`\`\`bash
   cd backend/
   ../scripts/deploy-backend.sh
   \`\`\`

5. **Deploy Frontend**:
   \`\`\`bash
   cd frontend/
   ../scripts/deploy-frontend.sh
   \`\`\`

6. **Verify Deployment**:
   \`\`\`bash
   cd scripts/
   ./verify-deployment.sh
   \`\`\`

## Documentation

- **Deployment Guide**: docs/DEPLOYMENT_GUIDE.md
- **Architecture Overview**: docs/JobQuest_Navigator_AWS_Deployment_Architecture.md
- **Troubleshooting**: docs/TROUBLESHOOTING_GUIDE.md
- **API Documentation**: Check backend/docs/ for API specs

## Support

For issues and questions:
- Check troubleshooting guide
- Review CloudWatch logs
- Contact development team

---
*Generated by JobQuest Navigator Release Packaging System*
EOF

# Create checksums file
print_status "Generating checksums..."
cd "$RELEASE_DIR"
find . -type f -exec sha256sum {} \; > CHECKSUMS.txt
cd - > /dev/null

# =============================================================================
# Clean Up Sensitive Files
# =============================================================================

print_status "Cleaning up sensitive files..."

# Remove sensitive files and directories
find "$RELEASE_DIR" -name "*.pyc" -delete
find "$RELEASE_DIR" -name "__pycache__" -type d -exec rm -rf {} + 2>/dev/null || true
find "$RELEASE_DIR" -name ".env" -delete 2>/dev/null || true
find "$RELEASE_DIR" -name "*.log" -delete 2>/dev/null || true
find "$RELEASE_DIR" -name ".DS_Store" -delete 2>/dev/null || true
find "$RELEASE_DIR" -name "node_modules" -type d -exec rm -rf {} + 2>/dev/null || true
find "$RELEASE_DIR" -name "venv" -type d -exec rm -rf {} + 2>/dev/null || true
find "$RELEASE_DIR" -name ".git" -type d -exec rm -rf {} + 2>/dev/null || true

# Remove development databases
rm -f "$RELEASE_DIR/backend/db.sqlite3" 2>/dev/null || true
rm -f "$RELEASE_DIR/backend/db_local.sqlite3" 2>/dev/null || true

# Remove temporary files
rm -rf "$RELEASE_DIR/backend/staticfiles" 2>/dev/null || true
rm -rf "$RELEASE_DIR/frontend/build" 2>/dev/null || true
rm -rf "$RELEASE_DIR/frontend/dist" 2>/dev/null || true

# =============================================================================
# Create Installation Script
# =============================================================================

print_status "Creating installation script..."

cat > "$RELEASE_DIR/install.sh" << 'EOF'
#!/bin/bash

# JobQuest Navigator - Installation Script
# This script helps with initial setup and configuration

set -e

echo "========================================"
echo "JobQuest Navigator Installation Script"
echo "========================================"
echo

# Check prerequisites
echo "Checking prerequisites..."

if ! command -v aws &> /dev/null; then
    echo "ERROR: AWS CLI not found. Please install AWS CLI first."
    exit 1
fi

if ! command -v python &> /dev/null; then
    echo "ERROR: Python not found. Please install Python 3.9+ first."
    exit 1
fi

if ! command -v node &> /dev/null; then
    echo "ERROR: Node.js not found. Please install Node.js 18+ first."
    exit 1
fi

if ! aws sts get-caller-identity > /dev/null 2>&1; then
    echo "ERROR: AWS CLI not configured. Please run 'aws configure' first."
    exit 1
fi

echo "✓ Prerequisites check passed"
echo

# Setup configuration
echo "Setting up configuration..."

if [ ! -f "configs/.env" ]; then
    if [ -f "configs/environment.env" ]; then
        cp configs/environment.env configs/.env
        echo "✓ Created configs/.env from template"
        echo "⚠ Please edit configs/.env with your AWS configuration before proceeding"
    else
        echo "ERROR: Configuration template not found"
        exit 1
    fi
else
    echo "✓ Configuration file already exists"
fi

# Make scripts executable
echo "Making scripts executable..."
chmod +x scripts/*.sh
echo "✓ Scripts are now executable"

echo
echo "========================================"
echo "Installation completed successfully!"
echo "========================================"
echo
echo "Next steps:"
echo "1. Edit configs/.env with your AWS configuration"
echo "2. Run: scripts/deploy-infrastructure.sh"
echo "3. Run: scripts/deploy-backend.sh"
echo "4. Run: scripts/deploy-frontend.sh"
echo "5. Run: scripts/verify-deployment.sh"
echo
echo "For detailed instructions, see docs/DEPLOYMENT_GUIDE.md"
EOF

chmod +x "$RELEASE_DIR/install.sh"

# =============================================================================
# Create Documentation Index
# =============================================================================

print_status "Creating documentation index..."

cat > "$RELEASE_DIR/README.md" << EOF
