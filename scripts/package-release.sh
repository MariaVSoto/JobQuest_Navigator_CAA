## 🏗️ Architecture

JobQuest Navigator uses a modern serverless architecture on AWS:

- **Frontend**: React SPA hosted on S3 with CloudFront
- **Backend**: Django REST API running on Lambda with API Gateway
- **Database**: MySQL on RDS
- **Storage**: S3 for static files and media
- **Monitoring**: CloudWatch for logs and metrics

## 💰 Cost Estimation

Monthly cost estimate for production deployment:
- **RDS MySQL (db.t3.micro)**: ~\$15
- **Lambda**: ~\$2 (1M requests)
- **API Gateway**: ~\$3 (1M requests)
- **S3**: ~\$0.12 (5GB storage)
- **Data Transfer**: ~\$0.90 (10GB)
- **Total**: ~\$21/month

